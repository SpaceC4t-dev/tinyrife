#!/bin/sh
# Embed the GLSL in this directory as C string constants: embed.sh OUT.h
# SRC_<NAME> for each *.comp; shaders that use the shared buffer/warp helpers get common.glsl prepended.
set -e
case "$1" in /*) out=$1 ;; *) out=$PWD/$1 ;; esac
cd "$(dirname "$0")"
esc() { sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/  "/' -e 's/$/\\n"/' "$@"; }
{
  echo "/* Generated by shaders/embed.sh from the GLSL files in shaders/ -- do not edit. */"
  for f in conv deconv prep update final unpack pack; do
    echo "static const char SRC_$(echo $f | tr a-z A-Z)[] ="
    case $f in prep|update|final) esc common.glsl "$f.comp" ;; *) esc "$f.comp" ;; esac
    echo "  ;"
  done
} > "$out"
