"""Regenerate shaders.h from the GLSL sources in ../gl_rife.py (single source of truth for the shaders)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import gl_rife as g

NAMES = [("CONV", g.CONV_SRC), ("DECONV", g.DECONV_SRC), ("PREP", g.PREP_SRC), ("UPDATE", g.UPDATE_SRC),
         ("FINAL", g.FINAL_SRC), ("UNPACK", g.UNPACK_SRC), ("PACK", g.PACK_SRC)]

def cstr(src):
  esc = lambda l: l.replace("\\", "\\\\").replace('"', '\\"')
  return "\n".join(f'  "{esc(l)}\\n"' for l in src.split("\n")[:-1] or [""]) + ";"

with open(os.path.join(HERE, "shaders.h"), "w") as f:
  f.write("/* Generated by gen_shaders.py from ../gl_rife.py -- do not edit. */\n")
  for n, s in NAMES: f.write(f"static const char SRC_{n}[] =\n{cstr(s)}\n\n")
